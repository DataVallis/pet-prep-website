/**
 * "{n} unit" in the right plural form: `kind` is min | hour | year, `n` a number (a decimal gets the `dec` form,
 * else the `other` form), `fmt` formats the number for the language.
 */
export function unit(lang, kind, n, fmt) {
  const P = PHRASES[lang], forms = P[kind];
  const v = Math.round(n * 10) / 10;
  const form = Number.isInteger(v) ? forms[new Intl.PluralRules(P.intl).select(v)] ?? forms.other : forms.dec ?? forms.other;
  return form.replace('{n}', fmt(v));
}
